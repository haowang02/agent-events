export function icon(name, attrs = {}) {
  const node = svgEl("svg", {
    viewBox: "0 0 24 24",
    "aria-hidden": "true",
    fill: "none",
    stroke: "currentColor",
    "stroke-width": "2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
    ...attrs,
    class: ["lucide", "lucide-" + name, attrs.class].filter(Boolean).join(" ")
  });
  node.innerHTML = ICONS[name];
  return node;
}

